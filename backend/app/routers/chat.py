from __future__ import annotations

import uuid
from typing import Optional

from fastapi import APIRouter, Depends
from pydantic import BaseModel

from app.agent import graph
from app.core import gate, security
from app.models import Identity

router = APIRouter(tags=["chat"])


class ChatBody(BaseModel):
    thread_id: str
    run_id: Optional[str] = None  # generated by the client so it can stop the run and follow its ledger
    message: str = ""
    file_id: Optional[str] = None
    ad: Optional[dict] = None  # AdContext, plus optional `text` for copy typed into the form
    use_memory: bool = True


@router.post("/chat")
def chat(body: ChatBody, identity: Identity = Depends(security.current_identity)) -> dict:
    run_id = body.run_id or str(uuid.uuid4())
    gate.open_run(identity, run_id, thread_id=body.thread_id, input_summary=body.message, memory_enabled=body.use_memory)
    try:
        result = graph.run_turn(identity, thread_id=body.thread_id, run_id=run_id, message=body.message, file_id=body.file_id, ad=body.ad, use_memory=body.use_memory)
    except Exception:
        gate.close_run(run_id, "error")
        raise
    # Record the intent on the run, in the vocabulary of the `runs` collection.
    gate.open_run(identity, run_id, intent={"approve_release": "approve", "other": None}.get(result.get("intent"), result.get("intent")))
    gate.close_run(run_id, result.get("status", "completed"), tokens=result.get("tokens"), memories_used=[m["id"] for m in result.get("memories_used", [])])
    return {
        "reply": result["reply"], "cards": result.get("cards", []), "memories_used": result.get("memories_used", []),
        "run_id": run_id, "intent": result.get("intent"), "status": result.get("status", "completed"),
        "tokens": result.get("tokens", {"in": 0, "out": 0}), "grounding": result.get("grounding"),
    }

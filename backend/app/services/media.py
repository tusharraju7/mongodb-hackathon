"""Media in and out. The review always runs on text, so audio and images are turned into text once.

In:   audio -> ElevenLabs Scribe transcript        image -> fast model reads the text and describes it
Out:  audio -> ElevenLabs text-to-speech           image -> brand template rendered in code

Images are rendered from a template, never generated by a model, so rates and fine print appear
exactly as reviewed.
"""
from __future__ import annotations

import io
import re
from functools import lru_cache
from typing import Optional

from pydantic import BaseModel, Field

from app.agent import prompts
from app.core import llm
from app.core.config import get_settings
from app.core.db import bucket, oid

AUDIO_TYPES = {"audio/mpeg", "audio/mp3", "audio/wav", "audio/x-wav", "audio/mp4", "audio/x-m4a", "audio/m4a", "audio/webm", "audio/ogg"}
IMAGE_TYPES = {"image/png", "image/jpeg", "image/webp", "image/gif"}
TTS_MODEL = "eleven_multilingual_v2"  # handles English and French with one voice
STT_MODEL = "scribe_v1"


class UnsupportedMedia(Exception):
    pass


def kind_of(mime: str) -> str:
    mime = (mime or "").split(";")[0].strip().lower()
    if mime in AUDIO_TYPES:
        return "audio"
    if mime in IMAGE_TYPES:
        return "image"
    raise UnsupportedMedia(f"Unsupported file type: {mime or 'unknown'}. Upload audio (mp3, wav, m4a) or an image (png, jpg).")


# ---------------------------------------------------------------- storage (GridFS)


def store(data: bytes, mime: str, filename: str = "upload", db=None) -> str:
    b = bucket() if db is None else __import__("gridfs").GridFSBucket(db)
    return str(b.upload_from_stream(filename, io.BytesIO(data), metadata={"mime": mime}))


def open_file(file_id: str, db=None) -> tuple[bytes, str]:
    b = bucket() if db is None else __import__("gridfs").GridFSBucket(db)
    stream = b.open_download_stream(oid(file_id))
    return stream.read(), (stream.metadata or {}).get("mime", "application/octet-stream")


def delete(file_id: str, db=None) -> None:
    b = bucket() if db is None else __import__("gridfs").GridFSBucket(db)
    try:
        b.delete(oid(file_id))
    except Exception:
        pass  # already gone


# ---------------------------------------------------------------- audio


@lru_cache
def _eleven():
    from elevenlabs.client import ElevenLabs

    return ElevenLabs(api_key=get_settings().elevenlabs_api_key)


@lru_cache
def voice_id() -> str:
    """The configured stock voice, or the first premade voice on the account. Never a cloned voice."""
    configured = get_settings().elevenlabs_voice_id
    if configured:
        return configured
    voices = _eleven().voices.search(page_size=50).voices
    premade = [v for v in voices if (getattr(v, "category", "") or "") == "premade"] or voices
    return premade[0].voice_id


def transcribe_bytes(data: bytes, filename: str = "ad.mp3") -> str:
    result = _eleven().speech_to_text.convert(model_id=STT_MODEL, file=(filename, io.BytesIO(data)), tag_audio_events=False)
    return (result.text or "").strip()


def transcribe(file_id: str, db=None) -> str:
    data, _ = open_file(file_id, db)
    return transcribe_bytes(data)


def synthesize_bytes(text: str, language: str = "en") -> bytes:
    chunks = _eleven().text_to_speech.convert(voice_id(), text=text, model_id=TTS_MODEL, output_format="mp3_44100_128", language_code=None)
    return b"".join(chunks)


def synthesize_speech(text: str, language: str = "en", db=None) -> str:
    return store(synthesize_bytes(text, language), "audio/mpeg", "regenerated.mp3", db)


# ---------------------------------------------------------------- image in


class ImageReading(BaseModel):
    text: str = Field(description="Every piece of text in the image, exactly as written, in reading order.")
    visual_notes: str = Field(description="Two or three sentences on what the image shows.")
    fine_print_present: bool
    fine_print_legible: bool = Field(description="False when fine print is present but too small or blurred to read reliably. True when there is none.")
    people_present: bool


def read_image_bytes(data: bytes, mime: str, *, usage: Optional[llm.TokenUsage] = None, run_id: Optional[str] = None) -> dict:
    reading = llm.call_structured(
        llm.fast_model(), ImageReading, system=prompts.READ_IMAGE_SYSTEM,
        user=[llm.image_block(data, mime), {"type": "text", "text": "Read this advertisement image."}],
        label="read_image", usage=usage, run_id=run_id, intent="review",
    )
    return reading.model_dump()


def read_image(file_id: str, db=None, **kw) -> dict:
    data, mime = open_file(file_id, db)
    return read_image_bytes(data, mime, **kw)


# ---------------------------------------------------------------- image out (brand template)

WIDTH, HEIGHT = 1200, 628
GREEN, CREAM, GOLD = (16, 60, 44), (245, 241, 230), (214, 178, 94)
FINE_PRINT = re.compile(r"(subject to credit approval|conditions apply|sous réserve|des conditions s.appliquent|unsubscribe|se désabonner)", re.I)
AMOUNT = re.compile(r"(\$\s?\d[\d,\.]*|\d[\d\s  ,\.]*\$)")


def _sentences(copy: str) -> list[str]:
    # Split after sentence punctuation, but not inside a number such as 20.99 or a host such as tamarack.test.
    parts = re.split(r"(?<=[.!?])\s+(?=[A-ZÀ-ÖØ-Þ0-9$«\"'])", copy.strip())
    return [p.strip() for p in parts if p.strip()]


def layout(copy: str) -> dict:
    """Split reviewed copy into headline, body and fine print. No wording is changed or dropped."""
    sentences = _sentences(copy)
    fine = [s for s in sentences if FINE_PRINT.search(s)]
    rest = [s for s in sentences if s not in fine]
    headline = next((s for s in rest if AMOUNT.search(s)), rest[0] if rest else "")
    body = [s for s in rest if s != headline]
    return {"headline": headline, "body": body, "fine_print": fine}


FONT_CANDIDATES = [
    "/System/Library/Fonts/Supplemental/Arial.ttf",            # macOS
    "/Library/Fonts/Arial.ttf",
    "/System/Library/Fonts/Helvetica.ttc",
    "C:/Windows/Fonts/arial.ttf",                              # Windows
    "C:/Windows/Fonts/segoeui.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",         # Linux
    "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
]


@lru_cache
def _font_path() -> Optional[str]:
    import os

    override = os.environ.get("BANNER_FONT")
    return next((p for p in ([override] if override else []) + FONT_CANDIDATES if p and os.path.exists(p)), None)


def _font(size: int):
    from PIL import ImageFont

    path = _font_path()
    return ImageFont.truetype(path, size) if path else ImageFont.load_default(size=size)


def _wrap(draw, text: str, font, max_width: int) -> list[str]:
    lines, line = [], ""
    for word in text.split():
        trial = f"{line} {word}".strip()
        if draw.textlength(trial, font=font) <= max_width or not line:
            line = trial
        else:
            lines.append(line)
            line = word
    return lines + ([line] if line else [])


def render_image_bytes(copy: str, *, language: str = "en", card_name: str = "Tamarack Cashback Card") -> bytes:
    from PIL import Image, ImageDraw

    # Pillow's built-in font has no accented letters. Rendering "crédit" with missing glyphs would
    # produce an image that does not say what was reviewed, so refuse instead.
    if _font_path() is None and any(ord(ch) > 127 for ch in copy + card_name):
        raise UnsupportedMedia("No font with accented characters was found on this machine. Set BANNER_FONT to a .ttf file.")

    parts = layout(copy)
    img = Image.new("RGB", (WIDTH, HEIGHT), GREEN)
    draw = ImageDraw.Draw(img)
    draw.rectangle([0, 0, WIDTH, 10], fill=GOLD)
    margin, max_width, y = 64, WIDTH - 128, 56

    def block(text: str, size: int, fill, gap: int) -> None:
        nonlocal y
        font = _font(size)
        for line in _wrap(draw, text, font, max_width):
            draw.text((margin, y), line, font=font, fill=fill)
            y += int(size * 1.25)
        y += gap

    block(card_name, 26, GOLD, 18)
    # Shrink the headline until the whole ad fits; the fine print never drops below a legible size.
    for headline_size in (64, 56, 48, 40, 34):
        probe = ImageDraw.Draw(Image.new("RGB", (WIDTH, HEIGHT)))
        need = len(_wrap(probe, parts["headline"], _font(headline_size), max_width)) * headline_size * 1.25
        need += sum(len(_wrap(probe, s, _font(30), max_width)) * 30 * 1.25 + 10 for s in parts["body"])
        need += len(_wrap(probe, " ".join(parts["fine_print"]), _font(20), max_width)) * 20 * 1.25
        if y + need + 60 <= HEIGHT:
            break
    block(parts["headline"], headline_size, CREAM, 22)
    for sentence in parts["body"]:
        block(sentence, 30, CREAM, 10)
    fine = " ".join(parts["fine_print"])
    if fine:
        font = _font(20)
        lines = _wrap(draw, fine, font, max_width)
        y = max(y, HEIGHT - 36 - int(len(lines) * 25))
        for line in lines:
            draw.text((margin, y), line, font=font, fill=CREAM)
            y += 25
    out = io.BytesIO()
    img.save(out, format="PNG")
    return out.getvalue()


def render_image(copy: str, *, language: str = "en", offer: Optional[dict] = None, db=None) -> str:
    name = (offer or {}).get("card_name_fr" if language == "fr" else "card_name") or "Tamarack Cashback Card"
    return store(render_image_bytes(copy, language=language, card_name=name), "image/png", "regenerated.png", db)
